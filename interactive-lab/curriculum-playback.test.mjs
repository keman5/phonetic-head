import {test} from 'node:test';
import assert from 'node:assert/strict';
import {launchBrowser} from './browser-test-utils.mjs';

test('connected lesson playback preserves audio, seek, speed, slow motion and cancellation', {timeout:120000}, async t => {
  const browser = await launchBrowser();
  t.after(() => browser.close());
  const page = await browser.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:4173/lab.html?lesson=dog-sentence', {waitUntil:'networkidle'});
  await page.waitForFunction(() => window.labSnapshot?.().ready);
  const snapshot = () => page.evaluate(() => window.labSnapshot());
  const setRange = async (id, value) => page.locator('#' + id).evaluate((input, value) => {
    input.value = value; input.dispatchEvent(new Event('input', {bubbles:true}));
  }, value);
  const choose = async (id, value) => {
    await page.locator(`#${id} .select-trigger`).click();
    await page.locator(`#${id} [role="option"][data-value="${value}"]`).click();
  };
  assert.equal((await snapshot()).sound, 'lesson:dog-sentence');
  assert.equal((await snapshot()).audio.rate, .85);
  assert.equal((await snapshot()).audio.playbackRate, .85);
  assert.equal(await page.locator('#speed-value').textContent(), '0.85 ×');
  await page.waitForFunction(() => {
    const duration = labSnapshot().audio.duration;
    return duration > 0 && document.querySelector('#time-label').textContent.includes('/ ' + duration.toFixed(1));
  });
  await page.locator('#course-listen').click();
  await page.waitForFunction(() => labSnapshot().audio.currentTime > .2);
  assert.match((await snapshot()).audio.src, /female\/lesson-dog-sentence.wav$/);
  await page.locator('#play').click();
  assert.equal((await snapshot()).audio.paused, true);
  await setRange('timeline', 700);
  await page.waitForFunction(() => Math.abs(labSnapshot().progress - .7) < .001);
  assert((await snapshot()).pose.wordIndex >= 3);
  await setRange('speed', 1.5);
  await choose('voice', 'male');
  assert.equal((await snapshot()).progress, 0);
  assert.equal((await snapshot()).audio.rate, 1.5);
  assert(Math.abs((await snapshot()).audio.playbackRate - 1.5) < 1e-9);
  await page.locator('#course-listen').click();
  await page.waitForFunction(() => labSnapshot().audio.currentTime > .1);
  await page.locator('#course-stage-1').click();
  await page.waitForFunction(() => labSnapshot().sound === 'lesson:dog-word' && !labSnapshot().playing);
  assert.equal((await snapshot()).progress, 0);
  assert.equal((await snapshot()).audio.paused, true);
  await page.locator('#course-stage-3').click();
  await page.locator('#watch-demo').click();
  await page.waitForFunction(() => labSnapshot().progress > .02);
  const slow = await snapshot();
  assert.equal(slow.audio.paused, false);
  assert.equal(slow.audio.muted, false);
  assert(Math.abs(slow.audio.playbackRate - .65) < 1e-9);
  assert(Math.abs(slow.progress - slow.audio.currentTime / slow.audio.duration) < .035, 'mouth follows the audio clock at slow speed');
  await page.locator('#play').click();
  await page.locator('#listen-demo').click();
  await page.waitForFunction(() => labSnapshot().progress >= 1 && !labSnapshot().playing, {}, {timeout:20000});
  assert.equal((await snapshot()).pose.wordIndex, -1);
  assert.equal((await snapshot()).airVisible, false);
  assert.equal(await page.locator('#course-text [aria-current]').count(), 0);
  assert((await page.evaluate(() => learningSnapshot())).done.includes('listen'));
  await choose('course-series', 'milk');
  assert.equal((await snapshot()).sound, 'lesson:milk-sound');
  assert.deepEqual((await page.evaluate(() => learningSnapshot())).done, []);

  await page.route('**/male/lesson-cat-word.wav', route => route.fulfill({status:503, body:'Unavailable'}));
  await choose('course-series', 'cat');
  await page.locator('#course-stage-1').click();
  await page.waitForFunction(() => document.querySelector('#audio-status').textContent.includes('失败'));
  await page.unroute('**/male/lesson-cat-word.wav');
  await page.locator('#watch-demo').click();
  await page.waitForFunction(() => labSnapshot().audio.currentTime > .1);
  assert.equal((await snapshot()).playing, true);
  assert.equal((await snapshot()).audio.paused, false);
  assert(Math.abs((await snapshot()).audio.playbackRate - .65) < 1e-9);
  await choose('library-mode', 'ipa');
  assert.equal((await snapshot()).playing, false);
  assert.deepEqual(errors, []);
});
